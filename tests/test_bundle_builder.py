def test_skip_env_var_short_circuits(tmp_path, monkeypatch):
    static, base = _make_static_tree(tmp_path)

    # Make src newer so it would normally rebuild.
    future = time.time() + 10
    os.utime(static / "src" / "main.js", (future, future))

    monkeypatch.setenv("ATLASFORGE_SKIP_BUNDLE_BUILD", "1")
    # Install a npm that would FAIL — proves we never invoked it.
    _install_fake_npm(tmp_path / "bin", monkeypatch, behavior="fail")

    result = ensure_bundle_fresh(static, base)
    assert result["status"] == "skipped"
    assert "ATLASFORGE_SKIP_BUNDLE_BUILD" in result["reason"]


def test_no_npm_returns_no_npm_status(tmp_path, monkeypatch):
    static, base = _make_static_tree(tmp_path)
    monkeypatch.delenv("ATLASFORGE_SKIP_BUNDLE_BUILD", raising=False)

    future = time.time() + 10
    os.utime(static / "src" / "main.js", (future, future))

    # Empty PATH so no npm is reachable.
    monkeypatch.setenv("PATH", "/nonexistent")

    result = ensure_bundle_fresh(static, base)
    assert result["status"] == "no_npm"


def test_build_failure_is_reported_not_raised(tmp_path, monkeypatch):
    static, base = _make_static_tree(tmp_path)
    monkeypatch.delenv("ATLASFORGE_SKIP_BUNDLE_BUILD", raising=False)

    future = time.time() + 10
    os.utime(static / "src" / "main.js", (future, future))

    _install_fake_npm(tmp_path / "bin", monkeypatch, behavior="fail")

    # Must not raise even though the build exits non-zero.
    result = ensure_bundle_fresh(static, base)
    assert result["status"] == "build_failed"
    assert result["returncode"] == 1


def test_force_rebuild_bypasses_freshness_check(tmp_path, monkeypatch):
    static, base = _make_static_tree(tmp_path)
    monkeypatch.delenv("ATLASFORGE_SKIP_BUNDLE_BUILD", raising=False)

    bundle = static / "dist" / "bundle.min.js"
    _install_fake_npm(tmp_path / "bin", monkeypatch, behavior="success",
                      touch_target=bundle)

    # Bundle is fresh — without force, we'd skip. With force, we rebuild.
    result = ensure_bundle_fresh(static, base, force=True)
    assert result["status"] == "rebuilt"
    assert result["reason"] == "forced rebuild"


def test_no_package_json_falls_back_gracefully(tmp_path, monkeypatch):
    static, base = _make_static_tree(tmp_path)
    monkeypatch.delenv("ATLASFORGE_SKIP_BUNDLE_BUILD", raising=False)

    (base / "package.json").unlink()
    future = time.time() + 10
    os.utime(static / "src" / "main.js", (future, future))

    _install_fake_npm(tmp_path / "bin", monkeypatch, behavior="success")

    result = ensure_bundle_fresh(static, base)
    assert result["status"] == "no_package_json"
